use std::collections::BTreeMap;
use std::fs;
use std::io::{self, Write};
use std::path::{Path, PathBuf};
use std::process::Command;

#[derive(serde::Deserialize)]
struct MonitorInfo {
    name: String,
}

pub fn get_hyprpaper_conf_path() -> PathBuf {
    if let Some(home) = std::env::var_os("HOME") {
        PathBuf::from(home).join(".config/hypr/hyprpaper.conf")
    } else {
        PathBuf::from(".config/hypr/hyprpaper.conf")
    }
}

pub fn get_connected_monitors() -> Vec<String> {
    if let Ok(output) = Command::new("hyprctl").args(["monitors", "-j"]).output()
        && output.status.success()
        && let Ok(monitors) = serde_json::from_slice::<Vec<MonitorInfo>>(&output.stdout)
    {
        return monitors.into_iter().map(|m| m.name).collect();
    }
    Vec::new()
}

pub fn parse_hyprpaper_conf(content: &str) -> (BTreeMap<String, String>, Option<String>) {
    let mut mon_map = BTreeMap::new();
    let mut fallback = None;

    let mut in_block = false;
    let mut cur_mon = String::new();
    let mut cur_path = String::new();

    for line in content.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with("wallpaper") && trimmed.contains('{') {
            in_block = true;
            cur_mon.clear();
            cur_path.clear();
            continue;
        }
        if in_block {
            if trimmed.contains('}') {
                in_block = false;
                if !cur_path.is_empty() {
                    if cur_mon.is_empty() {
                        fallback = Some(cur_path.clone());
                    } else {
                        mon_map.insert(cur_mon.clone(), cur_path.clone());
                    }
                }
                continue;
            }
            if let Some((k, v)) = trimmed.split_once('=') {
                let key = k.trim();
                let val = v.trim();
                if key == "monitor" {
                    cur_mon = val.to_string();
                } else if key == "path" {
                    cur_path = val.to_string();
                }
            }
        }
    }

    (mon_map, fallback)
}

pub fn serialize_hyprpaper_conf(mon_map: &BTreeMap<String, String>, fallback: Option<&str>) -> String {
    let mut out = String::from("# Auto-generated by inerium-wallpaper\n");
    for (mon, path) in mon_map {
        out.push_str(&format!(
            "wallpaper {{\n    monitor = {}\n    path = {}\n    fit_mode = cover\n}}\n\n",
            mon, path
        ));
    }
    let fb = fallback.or_else(|| mon_map.values().next().map(|s| s.as_str())).unwrap_or("");
    if !fb.is_empty() {
        out.push_str(&format!(
            "wallpaper {{\n    monitor = \n    path = {}\n    fit_mode = cover\n}}\n\n",
            fb
        ));
    }
    out.push_str("splash = false\n");
    out
}

pub fn write_hyprpaper_conf(path: &Path, mon_map: &BTreeMap<String, String>, fallback: Option<&str>) -> io::Result<()> {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent)?;
    }
    let content = serialize_hyprpaper_conf(mon_map, fallback);
    let tmp_path = path.with_extension("tmp");
    let mut file = fs::File::create(&tmp_path)?;
    file.write_all(content.as_bytes())?;
    file.sync_all()?;
    drop(file);
    fs::rename(tmp_path, path)?;
    Ok(())
}

pub fn apply_wallpaper(image_path: &Path, target_monitor: Option<&str>, notify: bool) -> Result<(), String> {
    if !image_path.exists() {
        return Err(format!("Wallpaper image not found: {}", image_path.display()));
    }
    let abs_path = image_path.canonicalize().map_err(|e| e.to_string())?;
    let path_str = abs_path.to_str().ok_or_else(|| "Invalid UTF-8 in image path".to_string())?;

    let conf_path = get_hyprpaper_conf_path();
    let existing_content = fs::read_to_string(&conf_path).unwrap_or_default();
    let (mut mon_map, mut fallback) = parse_hyprpaper_conf(&existing_content);

    let connected = get_connected_monitors();
    let target = target_monitor.unwrap_or("all").trim();

    let notify_title = if target.eq_ignore_ascii_case("all") {
        let targets = if !connected.is_empty() {
            connected
        } else {
            mon_map.keys().cloned().collect()
        };
        for mon in &targets {
            let _ = Command::new("hyprctl")
                .args(["hyprpaper", "wallpaper", &format!("{mon},{path_str}")])
                .output();
            mon_map.insert(mon.clone(), path_str.to_string());
        }
        fallback = Some(path_str.to_string());
        "Обои обновлены (все экраны)".to_string()
    } else {
        let _ = Command::new("hyprctl")
            .args(["hyprpaper", "wallpaper", &format!("{target},{path_str}")])
            .output();
        mon_map.insert(target.to_string(), path_str.to_string());

        // Mirror eDP-2 <-> eDP-1 if alternate connector is present
        if target == "eDP-2" && connected.contains(&"eDP-1".to_string()) {
            mon_map.insert("eDP-1".to_string(), path_str.to_string());
        } else if target == "eDP-1" && connected.contains(&"eDP-2".to_string()) {
            mon_map.insert("eDP-2".to_string(), path_str.to_string());
        }

        if fallback.is_none() {
            fallback = Some(path_str.to_string());
        }
        format!("Обои обновлены ({target})")
    };

    write_hyprpaper_conf(&conf_path, &mon_map, fallback.as_deref())
        .map_err(|e| format!("Failed writing hyprpaper.conf: {e}"))?;

    if notify {
        let filename = abs_path.file_name().and_then(|f| f.to_str()).unwrap_or("image");
        let _ = Command::new("notify-send")
            .args(["-a", "Обои", "-i", path_str, &notify_title, filename])
            .output();
    }

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_parse_and_serialize_hyprpaper_conf() {
        let sample = r#"
# Sample config
wallpaper {
    monitor = DP-1
    path = /home/user/wall1.png
    fit_mode = cover
}

wallpaper {
    monitor = HDMI-A-1
    path = /home/user/wall2.png
    fit_mode = cover
}

wallpaper {
    monitor = 
    path = /home/user/fallback.png
    fit_mode = cover
}

splash = false
"#;
        let (mon_map, fallback) = parse_hyprpaper_conf(sample);
        assert_eq!(mon_map.get("DP-1").map(|s| s.as_str()), Some("/home/user/wall1.png"));
        assert_eq!(mon_map.get("HDMI-A-1").map(|s| s.as_str()), Some("/home/user/wall2.png"));
        assert_eq!(fallback.as_deref(), Some("/home/user/fallback.png"));

        let serialized = serialize_hyprpaper_conf(&mon_map, fallback.as_deref());
        assert!(serialized.contains("monitor = DP-1"));
        assert!(serialized.contains("monitor = HDMI-A-1"));
        assert!(serialized.contains("path = /home/user/fallback.png"));
        assert!(serialized.contains("splash = false"));
    }
}
